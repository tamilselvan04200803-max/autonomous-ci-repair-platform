"""Immutable Pydantic v2 domain models for Aegis-CI (Milestone A1)."""

from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


def utcnow() -> datetime:
    """Return timezone-aware UTC timestamp."""
    return datetime.now(tz=UTC)


class RunState(StrEnum):
    """Lifecycle states of an Aegis-CI run (Master Plan Section 4)."""

    RECEIVED = "RECEIVED"
    FETCHED = "FETCHED"
    TRIAGED = "TRIAGED"
    REFUSED = "REFUSED"
    REPRODUCED = "REPRODUCED"
    LOCALIZED = "LOCALIZED"
    REPAIRING = "REPAIRING"
    VERIFIED = "VERIFIED"
    GATED = "GATED"
    DELIVERED = "DELIVERED"
    ESCALATED = "ESCALATED"
    FAILED = "FAILED"


class FailureClass(StrEnum):
    """Supported deterministic v1 failure taxonomy plus UNCLASSIFIED fail-closed residue."""

    F1_TEST_REGRESSION = "F1"
    F2_LINT_FORMAT = "F2"
    F3_TYPE_ERROR = "F3"
    F4_DEPENDENCY_DRIFT = "F4"
    F5_FLAKY = "F5"
    UNCLASSIFIED = "UNCLASSIFIED"


class PolicyVerdict(StrEnum):
    """Per-rule or aggregate Policy Gate verdict."""

    ALLOW = "ALLOW"
    DENY = "DENY"
    ESCALATE = "ESCALATE"


class FailureEvent(BaseModel):
    """Webhook / run ingestion event identifying the failing CI workflow execution."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    run_id: str
    repo: str
    workflow_run_id: int
    run_attempt: int = 1
    head_sha: str = Field(min_length=7, max_length=64)
    base_branch: str
    delivery_id: str
    is_fork: bool = False
    actor: str = ""
    workflow_name: str = ""
    received_at: datetime = Field(default_factory=utcnow)


class Diagnosis(BaseModel):
    """Structured triage output from deterministic parsers or residue classifier."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    failure_class: FailureClass
    parser: str
    failing_command: str = ""
    error_summary: str
    failing_test_ids: tuple[str, ...] = ()
    error_files: tuple[str, ...] = ()
    error_codes: tuple[str, ...] = ()
    confidence: float = Field(ge=0.0, le=1.0)
    evidence_excerpt: str = ""


class ContextManifest(BaseModel):
    """Recorded localization provenance & token accounting (Section 6 / Section 7.5)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    method: str
    files: tuple[str, ...]
    token_counts: dict[str, int]
    total_tokens: int = Field(ge=0)
    symbols: tuple[str, ...] = ()


class SearchReplaceEdit(BaseModel):
    """Structured edit against a single repository-relative path."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    path: str
    search: str
    replace: str


class Patch(BaseModel):
    """Candidate patch generated by repair adapter."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    attempt: int = Field(ge=1)
    edits: tuple[SearchReplaceEdit, ...] = ()
    unified_diff: str
    diff_sha256: str = Field(min_length=64, max_length=64)
    changed_files: tuple[str, ...]
    added_lines: int = Field(ge=0)
    deleted_lines: int = Field(ge=0)
    rationale: str = ""


class VerificationReport(BaseModel):
    """Empirical sandbox verification report before and/or after candidate patch."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    reproduction_runs: int = Field(ge=0)
    reproduced_failures: int = Field(ge=0)
    junit_xml_sha256: str = ""
    passed_after_patch: bool = False
    exit_codes_before: tuple[int, ...] = ()
    exit_codes_after: tuple[int, ...] = ()
    lint_clean: bool = False
    typecheck_clean: bool = False
    network_disabled: bool = True
    read_only_rootfs: bool = True
    execution_notes: str = ""


class PolicyDecision(BaseModel):
    """Single rule evaluation outcome from YAML Policy Gate P1..P8."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    rule_id: str
    verdict: PolicyVerdict
    reason: str
    details: tuple[str, ...] = ()


class LLMCallRecord(BaseModel):
    """Metadata and cryptographic hashes for one LLM invocation or cassette replay."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    attempt: int = Field(ge=1)
    model_id: str
    parameter_hash: str
    prompt_tokens: int = Field(ge=0)
    completion_tokens: int = Field(ge=0)
    prompt_sha256: str
    response_sha256: str
    cached_replay: bool = False
    local_transcript_path: str = ""


class ToolVersions(BaseModel):
    """Environment & container versions bound into the evidence bundle."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    image_digest: str
    python_version: str
    lockfile_sha256: str
    aegis_version: str = "0.1.0"


EvidenceVerdict = Literal["DELIVERED", "REFUSED", "ESCALATED", "FAILED"]


class EvidenceBundle(BaseModel):
    """Complete tamper-evident evidence bundle exported after gate evaluation."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    schema_version: str = "aegis.evidence_bundle.v1"
    run_id: str
    repo: str
    head_sha: str
    verdict: EvidenceVerdict
    failure_event: FailureEvent
    diagnosis: Diagnosis
    reproduction: VerificationReport | None = None
    context_manifest: ContextManifest | None = None
    llm_calls: tuple[LLMCallRecord, ...] = ()
    attempts: tuple[Patch, ...] = ()
    attempt_verifications: tuple[VerificationReport, ...] = ()
    policy_decisions: tuple[PolicyDecision, ...] = ()
    final_diff_sha256: str | None = None
    tool_versions: ToolVersions
    chain_head_hash: str
    created_at: datetime = Field(default_factory=utcnow)
